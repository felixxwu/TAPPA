# Card icons sit beside 36 px titles (whole-pixel x4); HUD glyphs beside 18 px text (x2).
SHEET_SCALE = {"card": 4, "hud": 2}


def parse(name, art):
    rows = art.strip("\n").split("\n")
    width = len(rows[0])
    assert all(len(r) == width for r in rows), f"{name}: ragged rows"
    assert set("".join(rows)) <= {"#", "."}, f"{name}: only '#' and '.' allowed"
    return rows


def write_png(path, width, height, rgba):
    raw = b"".join(b"\x00" + bytes(rgba[y * width * 4:(y + 1) * width * 4]) for y in range(height))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def icon_rgba(rows):
    return [v for r in rows for c in r for v in ((255, 255, 255, 255) if c == "#" else (0, 0, 0, 0))]


