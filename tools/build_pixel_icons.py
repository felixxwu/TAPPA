def write_sheet(path, groups):
    cell_w, cell_h, cols, pad = 120, 112, 6, 8
    tiles = [(name, rows, SHEET_SCALE[kind]) for kind, icons in groups for name, rows in icons]
    width = cell_w * cols
    height = cell_h * ((len(tiles) + cols - 1) // cols)
    px = [[(24, 26, 30)] * width for _ in range(height)]

    def put(x, y, colour):
        if 0 <= x < width and 0 <= y < height:
            px[y][x] = colour

    for i, (name, rows, scale) in enumerate(tiles):
        ox, oy = (i % cols) * cell_w, (i // cols) * cell_h
        for y in range(oy + 2, oy + cell_h - 2):
            for x in range(ox + 2, ox + cell_w - 2):
                put(x, y, (38, 41, 47))
        # Each icon at its in-game scale; small HUD glyphs also get a x6 zoom beside it.
        shown = [scale] if scale >= 4 else [scale, 6]
        total = sum(len(rows[0]) * s for s in shown) + 12 * (len(shown) - 1)
        ix = ox + (cell_w - total) // 2
        for s in shown:
            iw, ih = len(rows[0]) * s, len(rows) * s
            iy = oy + pad + (84 - ih) // 2
            for ry, r in enumerate(rows):
                for rx, c in enumerate(r):
                    if c == "#":
                        for dy in range(s):
                            for dx in range(s):
                                put(ix + rx * s + dx, iy + ry * s + dy, (255, 255, 255))
            ix += iw + 12
        label = name.upper()
        lx = ox + (cell_w - (len(label) * 4 - 1) * 2) // 2
        for k, ch in enumerate(label):
            for gy, grow in enumerate(FONT[ch].split(",")):
                for gx, c in enumerate(grow):
                    if c == "#":
                        for dy in range(2):
                            for dx in range(2):
                                put(lx + (k * 4 + gx) * 2 + dx, oy + cell_h - 18 + gy * 2 + dy, (150, 160, 175))
    write_png(path, width, height, [v for row in px for (r, g, b) in row for v in (r, g, b, 255)])


def main():
    groups = []
    for kind, table, folder in (("card", CARD, "icons/cards"), ("hud", HUD, "icons/hud")):
        icons = []
        for name, art in table.items():
            rows = parse(name, art)
            write_png(f"{folder}/{name}.png", len(rows[0]), len(rows), icon_rgba(rows))
            icons.append((name, rows))
        groups.append((kind, icons))
    groups.append(("card", [(name, parse(name, art)) for name, art in OLD.items()]))
    if len(sys.argv) > 1:
        write_sheet(sys.argv[1], groups)


if __name__ == "__main__":
    main()
